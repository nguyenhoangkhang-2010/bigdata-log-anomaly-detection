"""Giao diện nguồn dữ liệu. Router chỉ biết `Repository`, không biết dữ liệu đến từ đâu
(demo trong bộ nhớ hay Elasticsearch của pipeline thật)."""
from __future__ import annotations

from datetime import datetime
from typing import Protocol

from ..schemas import (
    Alert, AnomalyDetail, AnomalyPage, ComponentStat, DataSource, EventTemplate, Level, LogPage, Meta,
    ModelEval, ModelName, ScoreDistribution, Severity, Summary, Timeline,
)


class Repository(Protocol):
    name: DataSource

    def meta(self) -> Meta: ...
    def summary(self) -> Summary: ...
    def timeline(self, bucket: str) -> Timeline: ...
    def components(self, limit: int) -> list[ComponentStat]: ...
    def alerts(self, severity: Severity | None, limit: int) -> list[Alert]: ...
    def anomalies(self, model: ModelName | None, only_flagged: bool, min_score: float | None, q: str | None,
                  sort: str, page: int, page_size: int) -> AnomalyPage: ...
    def anomaly_detail(self, block_id: str, model: ModelName | None) -> AnomalyDetail | None: ...
    def events(self, sort: str, limit: int) -> list[EventTemplate]: ...
    def models(self) -> list[ModelEval]: ...
    def score_distribution(self, model: ModelName, bins: int) -> ScoreDistribution | None: ...
    def logs(self, q: str | None, level: Level | None, component: str | None, block_id: str | None,
             start: datetime | None, end: datetime | None, page: int, page_size: int) -> LogPage: ...
